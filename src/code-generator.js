/**
 * Generates executable and API-ready Playwright script code from recorded action steps.
 */

function isLoginStep(step) {
  const url = step.url || '';
  const selector = step.selector || '';
  if (/accounts\.google\.com|signin\/identifier|challenge\/pwd|challenge\/dp|ServiceLogin/i.test(url)) return true;
  if (/#identifierId|input\[name="Passwd"\]|input\[name="password"\]|input\[type="password"\]/i.test(selector)) return true;
  return false;
}

function generateStandaloneScript(sessionName, steps = [], options = {}) {
  const { userDataDir = './profiles/default', headless = false } = options;

  const lines = [
    `/**`,
    ` * Auto-generated by AuStudio Playwright Stealth Recorder`,
    ` * Session: ${sessionName}`,
    ` * Date: ${new Date().toISOString()}`,
    ` *`,
    ` * Dapat dijalankan langsung: node script.js`,
    ` * Atau di-import ke API Service: const { runAutomation } = require('./script');`,
    ` */`,
    `const fs = require('fs');`,
    `const path = require('path');`,
    `const { launchStealthChrome } = require('../../src/stealth-browser');`,
    `const { humanClick, humanPaste, humanDelay } = require('../../src/human-behavior');`,
    ``,
    `/**`,
    ` * Fungsi utama automasi yang dapat dipanggil dari Service API`,
    ` * @param {Object} options - Parameter kustom (headless, dynamic inputs, etc.)`,
    ` */`,
    `async function runAutomation(options = {}) {`,
    `  const isHeadless = options.headless !== undefined ? options.headless : ${headless};`,
    `  const profilePath = options.userDataDir || path.resolve('${userDataDir.replace(/\\/g, '\\\\')}');`,
    ``,
    `  console.log('[AuStudio] Menjalankan Playwright dengan Human Behavior & Stealth Engine...');`,
    `  const { context } = await launchStealthChrome({`,
    `    userDataDir: profilePath,`,
    `    headless: isHeadless,`,
    `    extraArgs: ['--start-maximized']`,
    `  });`,
    ``,
    `  const page = context.pages().length > 0 ? context.pages()[0] : await context.newPage();`,
    `  page.setDefaultTimeout(options.timeout || 35000);`,
    ``,
    `  const downloadsDir = path.resolve(__dirname, 'downloads');`,
    `  if (!fs.existsSync(downloadsDir)) {`,
    `    fs.mkdirSync(downloadsDir, { recursive: true });`,
    `  }`,
    `  page.on('download', async (download) => {`,
    `    try {`,
    `      const filename = download.suggestedFilename() || \`speech_\${Date.now()}.wav\`;`,
    `      const savePath = path.join(downloadsDir, filename);`,
    `      console.log(\`[AuStudio ⬇️] Mengunduh file: \${filename}...\`);`,
    `      await download.saveAs(savePath);`,
    `      console.log(\`[AuStudio ✓] Berhasil disimpan di: \${savePath}\`);`,
    `    } catch (e) {`,
    `      console.warn('[AuStudio] Download notice:', e.message);`,
    `    }`,
    `  });`,
    ``,
    `  try {`
  ];

  let stepCounter = 0;
  for (let i = 0; i < steps.length; i++) {
    const step = steps[i];
    if (isLoginStep(step)) continue;
    stepCounter++;
    const stepNum = stepCounter;

    switch (step.type) {
      case 'navigate':
        lines.push(`    // Step ${stepNum}: Navigate`);
        lines.push(`    console.log('-> Navigating to:', ${JSON.stringify(step.url)});`);
        lines.push(`    await page.goto(${JSON.stringify(step.url)}, { waitUntil: 'domcontentloaded' });`);
        lines.push(`    await page.waitForTimeout(1000);`);
        lines.push(``);
        break;

      case 'click':
        lines.push(`    // Step ${stepNum}: Click on ${JSON.stringify(step.selector)}`);
        lines.push(`    console.log('-> 👤 Clicking:', ${JSON.stringify(step.selector)});`);
        lines.push(`    await humanClick(page, ${JSON.stringify(step.selector)});`);
        lines.push(`    await humanDelay(400, 900);`);
        lines.push(``);
        break;

      case 'dblclick':
        lines.push(`    // Step ${stepNum}: Double click on ${JSON.stringify(step.selector)}`);
        lines.push(`    console.log('-> 👤 Double clicking:', ${JSON.stringify(step.selector)});`);
        lines.push(`    await humanClick(page, ${JSON.stringify(step.selector)});`);
        lines.push(`    await humanDelay(50, 100);`);
        lines.push(`    await humanClick(page, ${JSON.stringify(step.selector)});`);
        lines.push(`    await humanDelay(400, 800);`);
        lines.push(``);
        break;

      case 'fill':
        lines.push(`    // Step ${stepNum}: Paste ${JSON.stringify(step.selector)}`);
        lines.push(`    console.log('-> 📋 Pasting:', ${JSON.stringify(step.selector)});`);
        lines.push(`    await humanPaste(page, ${JSON.stringify(step.selector)}, ${JSON.stringify(step.value || '')});`);
        lines.push(`    await humanDelay(500, 1000);`);
        lines.push(``);
        break;

      case 'press':
        lines.push(`    // Step ${stepNum}: Press key ${JSON.stringify(step.key)}`);
        lines.push(`    console.log('-> Pressing:', ${JSON.stringify(step.key)});`);
        if (step.selector) {
          lines.push(`    await page.press(${JSON.stringify(step.selector)}, ${JSON.stringify(step.key)});`);
        } else {
          lines.push(`    await page.keyboard.press(${JSON.stringify(step.key)});`);
        }
        lines.push(`    await page.waitForTimeout(300);`);
        lines.push(``);
        break;

      case 'select':
        lines.push(`    // Step ${stepNum}: Select ${JSON.stringify(step.value)} in ${JSON.stringify(step.selector)}`);
        lines.push(`    console.log('-> Selecting:', ${JSON.stringify(step.value)});`);
        lines.push(`    await page.waitForSelector(${JSON.stringify(step.selector)}, { state: 'visible', timeout: 10000 });`);
        lines.push(`    await page.selectOption(${JSON.stringify(step.selector)}, ${JSON.stringify(step.value)});`);
        lines.push(`    await page.waitForTimeout(500);`);
        lines.push(``);
        break;

      case 'scroll':
        lines.push(`    // Step ${stepNum}: Scroll window`);
        lines.push(`    await page.evaluate(({ x, y }) => window.scrollTo(x, y), { x: ${step.scrollX || 0}, y: ${step.scrollY || 0} });`);
        lines.push(`    await page.waitForTimeout(400);`);
        lines.push(``);
        break;

      case 'wait':
        lines.push(`    // Step ${stepNum}: Wait ${step.duration || 1000}ms`);
        lines.push(`    await page.waitForTimeout(${step.duration || 1000});`);
        lines.push(``);
        break;

      default:
        break;
    }
  }

  lines.push(`    console.log('[AuStudio] All recorded steps executed successfully!');`);
  lines.push(`    await page.waitForTimeout(1000);`);
  lines.push(`    return { success: true, totalSteps: ${stepCounter} };`);
  lines.push(`  } finally {`);
  lines.push(`    if (!options.keepOpen) {`);
  lines.push(`      await context.close();`);
  lines.push(`    }`);
  lines.push(`  }`);
  lines.push(`}`);
  lines.push(``);
  lines.push(`// Jika file ini dijalankan langsung lewat terminal (node script.js)`);
  lines.push(`if (require.main === module) {`);
  lines.push(`  runAutomation().catch(err => {`);
  lines.push(`    console.error('[AuStudio] Error running script:', err);`);
  lines.push(`    process.exit(1);`);
  lines.push(`  });`);
  lines.push(`}`);
  lines.push(``);
  lines.push(`module.exports = { runAutomation };`);

  return lines.join('\n');
}

function generateApiTemplate(sessionName) {
  return `/**
 * Template Service API (Express) untuk sesi: ${sessionName}
 * Gunakan file ini jika Anda ingin mengintegrasikannya ke backend API endpoint.
 */
const express = require('express');
const { runAutomation } = require('./script');

const app = express();
app.use(express.json());

// Endpoint untuk memicu automasi
app.post('/api/automation/run', async (req, res) => {
  try {
    const options = {
      headless: req.body.headless !== undefined ? req.body.headless : true,
      // Anda bisa menyisipkan parameter dinamis dari req.body di sini
    };

    console.log('[API] Triggering automation flow for ${sessionName}...');
    const result = await runAutomation(options);
    res.json({ success: true, result });
  } catch (err) {
    console.error('[API Error]:', err);
    res.status(500).json({ success: false, error: err.message });
  }
});

const PORT = process.env.SERVICE_PORT || 5000;
if (require.main === module) {
  app.listen(PORT, () => {
    console.log(\`Service API automasi berjalan di http://localhost:\${PORT}\`);
    console.log(\`POST http://localhost:\${PORT}/api/automation/run untuk mengeksekusi script.\`);
  });
}

module.exports = app;
`;
}

module.exports = {
  isLoginStep,
  generateStandaloneScript,
  generateApiTemplate
};
